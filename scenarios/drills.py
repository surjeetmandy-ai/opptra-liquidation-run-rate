"""Run the "we'll change some conditions" drills and write scenarios/drill_results.md.

python scenarios/drills.py
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from engine.config import Config  # noqa: E402
from engine.decide import build_plan  # noqa: E402
from engine.session import load_session  # noqa: E402
from engine.state import State  # noqa: E402

D = ROOT / "data"


def plan_for(**overrides):
    """Build the day-1 plan on the real data with some config values changed."""
    cfg = Config()
    for k, v in overrides.items():
        setattr(cfg, k, v)
    ds, _ = load_session(D, D / "no-state.json")  # the shipped data, nothing applied
    return build_plan(ds, State(), cfg), cfg


def summary(p):
    """The numbers one drill row needs: sell-through and net recovery (hold vs plan), exits, ad totals, how many of
    each kind of action, and the top three actions.
    """
    v = p.verdict
    kinds = {"price": 0, "ads_up": 0, "ads_down": 0, "exit": 0}
    for a in p.changes:
        if a.price_to != a.price_from:
            kinds["price"] += 1
        if a.ads_to > a.ads_from + 0.5:
            kinds["ads_up"] += 1
        if a.ads_to < a.ads_from - 0.5:
            kinds["ads_down"] += 1
        if a.exit_units:
            kinds["exit"] += 1
    return dict(
        st_hold=v["sell_through_hold"],
        st_plan=v["sell_through_plan"],
        rng=v["plan_range"],
        net_hold=v["hold"]["net"],
        net_plan=v["plan"]["net"],
        jobber_today=v["jobber_today"],
        exits=v["plan"]["exits"],
        left=v["plan"]["unsold"],
        n=len(p.changes),
        amz=p.ad_totals["plan"].get("amazon_ae", 0),
        noon=p.ad_totals["plan"].get("noon", 0),
        kinds=kinds,
        top=[a.headline() for a in p.changes[:3]],
        viol=len(p.violations),
    )


SCENARIOS = [
    ("Baseline (the brief)", {}, ""),
    (
        "Both ad budgets halved",
        {"ad_budget": {"amazon_ae": 750.0, "noon": 500.0}},
        "Allocation re-ranks: the money stays on the best converters; the weakest raises go first.",
    ),
    (
        "Noon ad budget = 0",
        {"ad_budget": {"amazon_ae": 1500.0, "noon": 0.0}},
        "Every Noon listing loses paid traffic; price and exits carry Noon on their own.",
    ),
    (
        "Deadline 30 days, not 60",
        {"horizon_days": 30},
        "Required run-rate doubles; more listings go critical, deeper first cuts, more exits now.",
    ),
    (
        "Jobber pays 40% of cost",
        {"jobber_pct": 0.40},
        "The bar a marketplace sale must clear goes up; ads on marginal listings stop paying; more exits.",
    ),
    (
        "Jobber pays 10% of cost",
        {"jobber_pct": 0.10},
        "Jobber is worth less, so selling on the marketplace is worth more effort; fewer exits.",
    ),
    ("15% marketplace fee", {"marketplace_fee_pct": 0.15}, "Every sale earns 15% less; ads that were marginal stop paying."),
    (
        "Parity ±3%, 1 price change a week",
        {"parity_band": 0.03, "max_price_changes": 1},
        "S06 and S08 are now outside the band: fixed first. Fewer, more careful cuts.",
    ),
]


def main():
    """Run every scenario, check none breaks a rule, print the table and write scenarios/drill_results.md."""
    base = None
    lines = [
        "# Scenario drills — what the tool does when the conditions change",
        "",
        "Generated by `python scenarios/drills.py` on the real data (plan for 5 Oct, day 1 of 60). "
        "Every scenario: zero rule violations.",
        "",
        "| Scenario | Actions | Sell-through: hold → plan (range) | Net recovery: hold → plan (AED) | Exit now | Left on day 60 | Ads/day Amazon · Noon | Price · ads↑ · ads↓ · exits |",
        "|---|---|---|---|---|---|---|---|",
    ]
    detail = []
    for name, ov, expect in SCENARIOS:
        p, cfg = plan_for(**ov)
        s = summary(p)
        assert s["viol"] == 0, (name, p.violations)
        base = base or s
        k = s["kinds"]
        lines.append(
            f"| {name} | {s['n']} | {s['st_hold']:.0%} → **{s['st_plan']:.0%}** ({s['rng'][0]:.0%}–{s['rng'][1]:.0%}) | "
            f"{s['net_hold']:,.0f} → **{s['net_plan']:,.0f}** | {s['exits']:,.0f} | {s['left']:,.0f} | "
            f"{s['amz']:,.0f} · {s['noon']:,.0f} | {k['price']} · {k['ads_up']} · {k['ads_down']} · {k['exit']} |"
        )
        detail.append(f"### {name}")
        if expect:
            detail.append(f"*What should happen:* {expect}")
        detail.append(
            f"*What the tool does:* {s['n']} actions; sell-through {s['st_plan']:.0%} (baseline {base['st_plan']:.0%}); "
            f"net AED {s['net_plan']:,.0f} (baseline {base['net_plan']:,.0f}, jobber-today {s['jobber_today']:,.0f}); "
            f"{s['exits']:,.0f} pairs exited now (baseline {base['exits']:,.0f}). Top three:"
        )
        for t in s["top"]:
            detail.append(f"- {t}")
        detail.append("")
    lines += [
        "",
        "Columns: *hold* = if nothing changes; *plan* = with today's actions. Range = 10th–90th percentile of conversion.",
        "",
    ]
    out = ROOT / "scenarios" / "drill_results.md"
    out.write_text("\n".join(lines + detail))
    print("\n".join(lines))
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
